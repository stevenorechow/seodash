// Writes emdash-plugin.jsonc from what the feature modules declare, so the manifest (the trust
// contract) cannot drift from the code. Run `npm run build` in the package root first.
//   node scripts/manifest.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { compose } from "../../dist/compose.js";
import { MODULES } from "../../dist/modules/marketplace.js";

const file = new URL("../emdash-plugin.jsonc", import.meta.url);
const built = compose(MODULES, { trusted: false });
// Publisher details are kept from the existing file; everything else is generated.
let existing = {};
try {
	existing = JSON.parse(readFileSync(file, "utf8").replace(/^\s*\/\/.*$/gm, ""));
} catch {
	existing = {};
}
const keep = (key, fallback) => existing[key] ?? fallback;

const manifest = {
	$schema: "./node_modules/@emdash-cms/plugin-cli/schemas/emdash-plugin.schema.json",
	slug: "seodash",
	name: "SEOdash",
	description: "Titles, social cards, structured data, content analysis, a site audit, instant indexing and publishing rules, built on EmDash's SEO fields.",
	keywords: ["seo", "structured-data", "open-graph", "indexnow", "audit"],
	version: JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).version,
	license: "GPL-3.0-only",
	publisher: keep("publisher", "did:plc:REPLACE_WITH_YOUR_PUBLISHER_DID"),
	author: keep("author", { name: "SEOdash contributors" }),
	security: keep("security", { url: "https://example.com/REPLACE-with-your-security-contact" }),
	...(existing.repo ? { repo: existing.repo } : {}),
	sections: {
		description: { file: "listing/description.md" },
		installation: { file: "listing/installation.md" },
		faq: { file: "listing/faq.md" },
		changelog: { file: "listing/changelog.md" },
	},
	release: {
		artifacts: {
			icon: { file: "icon.png" },
			screenshots: readdirSync(new URL("../listing/screenshots/", import.meta.url)).filter((f) => f.endsWith(".png")).sort().map((f) => ({ file: `listing/screenshots/${f}` })),
		},
	},
	// The only content the modules write is an entry's core SEO fields, which EmDash 1.5 refuses from the
	// sandbox (the panel shows them read-only), so this build does not ask to edit content.
	capabilities: [...built.capabilities.filter((capability) => capability !== "content:write"), ...(built.uses.beforePublish ? ["hooks.content-policy:register"] : [])].sort(),
	allowedHosts: [...built.allowedHosts].sort(),
	storage: built.storage,
	admin: built.admin,
};
writeFileSync(file, "// Generated by scripts/manifest.mjs. Edit publisher, author and security here; the rest is rewritten.\n" + JSON.stringify(manifest, null, "\t") + "\n");
console.log(`capabilities: ${manifest.capabilities.join(", ")}\nhosts: ${manifest.allowedHosts.join(", ")}\nstorage: ${Object.keys(manifest.storage).join(", ")}`);
